#!/usr/bin/env python3
"""Generates widget layouts and colour resources, one per theme.

Run from the repo root after changing a palette or the layout template:
    python3 tools/gen_widget_themes.py
"""
import pathlib

RES = pathlib.Path(__file__).resolve().parent.parent / "app/src/main/res"

PALETTES = {
    # Current look: charcoal with a gold accent
    "graphite": dict(bg="#EB15181E", table="#14FFFFFF", button="#26FFFFFF", text="#FFFFFFFF",
                     dim="#B3FFFFFF", faint="#80FFFFFF", accent="#FFFFC94D", icon="#FFFFFFFF"),
    # Alternative dark: deep navy with a mint accent
    "midnight": dict(bg="#F20B1430", table="#1F5B7BD5", button="#335B7BD5", text="#FFF2F6FF",
                     dim="#B3D4DEFF", faint="#8099AAD6", accent="#FF5EEAD4", icon="#FFE6EEFF"),
    # Light: warm off-white with a deep amber accent
    "light":    dict(bg="#F5FAFAF7", table="#0D000000", button="#14000000", text="#FF1A1C20",
                     dim="#A61A1C20", faint="#7A1A1C20", accent="#FFB45309", icon="#FF2A2D33"),
}
# "auto_X" follows the phone: light palette by day, X palette in dark mode.
AUTO = {"auto_graphite": "graphite", "auto_midnight": "midnight"}

def colors(entries):
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             "<!-- Generated by tools/gen_widget_themes.py. Do not edit by hand. -->", "<resources>"]
    lines += [f'    <color name="{n}">{v}</color>' for n, v in entries]
    lines.append("</resources>\n")
    return "\n".join(lines)

day, night = [], []
for name, pal in PALETTES.items():
    day += [(f"p_{name}_{role}", v) for role, v in pal.items()]
for name, dark in AUTO.items():
    day += [(f"p_{name}_{role}", v) for role, v in PALETTES["light"].items()]
    night += [(f"p_{name}_{role}", v) for role, v in PALETTES[dark].items()]

(RES / "values/colors_widget.xml").write_text(colors(day))
(RES / "values-night").mkdir(exist_ok=True)
(RES / "values-night/colors_widget.xml").write_text(colors(night))

TEMPLATE = (pathlib.Path(__file__).parent / "widget_template.xml").read_text()
for name in list(PALETTES) + list(AUTO):
    out = TEMPLATE.replace("@color/P_", f"@color/p_{name}_")
    out = out.replace("<!--HEADER-->", "<!-- Generated by tools/gen_widget_themes.py from widget_template.xml. -->")
    (RES / f"layout/widget_{name}.xml").write_text(out)
print("generated", len(PALETTES) + len(AUTO), "widget layouts")
